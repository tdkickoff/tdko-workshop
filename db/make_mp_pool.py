"""Writes functions/api/mp/_pool.js: every approved puzzle Multiplayer uses (the ok flag is kept for reference only) (not a route; never sent whole to phones).
A puzzle is 'ok' for the live site when it has already played as a daily puzzle, or is not on the calendar in the
next 6 months (Fast Break: 8 weeks), so a quiz night never spoils an upcoming day. Preview sites may use everything,
so the games can be tested before there is enough played stock.
Live-stat puzzles (fact_question.live=1) are only ok when re-checked in the last 7 days.
Run by make_seed.py at every release."""
import sqlite3, json, datetime, os
DB = os.environ.get('TDKO_DB', '/home/claude/db/tdko.db')
OUT = '/home/claude/tdko-site/functions/api/mp/_pool.js'
c = sqlite3.connect(DB); c.row_factory = sqlite3.Row
today = datetime.date.today()
GAP = {'fast-break': 56}

def rows(slug):
    return c.execute("""SELECT q.question_id id, q.ext_id, q.payload, q.live, q.checked_on, d.code diff,
        (SELECT group_concat(dd.date) FROM fact_schedule s JOIN dim_date dd USING(date_key) WHERE s.question_id=q.question_id) dates
        FROM fact_question q JOIN dim_game g USING(game_id) LEFT JOIN dim_difficulty d USING(difficulty_id)
        WHERE g.slug=? AND q.status='approved'""", (slug,)).fetchall()

def ok(r, slug):
    if r['live'] and not (r['checked_on'] and (today - datetime.date.fromisoformat(r['checked_on'])).days <= 7):
        return False
    gap = GAP.get(slug, 182)
    for d in (r['dates'] or '').split(','):
        if not d: continue
        dd = datetime.date.fromisoformat(d)
        if today <= dd <= today + datetime.timedelta(days=gap): return False   # still to play (or today's): keep it unspoiled
    return True

import re
# Fast Break question kinds, so a quiz mixes them (otherwise 'which country' questions dominate)
R=[('awards',r"ballon d'or|golden boot|golden ball|pfa |player of the (year|season)|footballer of the year"),
 ('laws',r"\b(card|offside|referee|var|penalty area|free kick|throw-in|corner kick|awarded|laws? of the game|how long|minutes)\b"),
 ('nation',r"\b(which|what) (country|nation|national team)\b|\bnationality\b|\bcountry (did|does|is|was)\b|represent(ed|s)? (at|in) international"),
 ('ground',r"\bstadium\b|\bground\b|\bplay(s|ed)? (their )?home (games|matches)"),
 ('manager',r"\bmanag(er|ed|es)\b|\bcoach(ed)?\b|\bboss\b"),
 ('nickname',r"\bnickname|\bknown as\b"),
 ('transfer',r"\btransfer|\bsign(ed|ing)\b|\bfee\b|\bjoin(ed)?\b"),
 ('worldcup',r"world cup|euro(s|pean championship)?\b|copa am|afcon|africa cup|nations league"),
 ('europe',r"champions league|european cup|uefa cup|europa|cup winners"),
 ('record',r"\b(most|record|first|youngest|oldest|fastest|highest|top scorer|all-time)\b"),
 ('year',r"\b(what|which) year\b|\bin what year\b|\bwhen did\b"),
 ('city',r"\bin which city|\bwhere (is|are|was|were|do|did)\b|\bwhich city\b"),
 ('howmany',r"^how many\b"),
 ('club',r"\b(which|what) (club|team|side)\b"),
 ('player',r"^who\b"),
]
def kind(q):
    s=q.lower()
    for k,p in R:
        if re.search(p,s): return k
    return 'other'
P = {'fb': [], 'wtb': [], 'cs': [], 'rh': []}
for r in rows('fast-break'):
    p = json.loads(r['payload'])
    P['fb'].append(dict(id=r['id'], q=p['q'], o=p['options'], d=(r['diff'] or p.get('d') or 'm').lower(), k=kind(p['q']), ok=ok(r, 'fast-break')))
for r in rows('whos-that-baller'):
    p = json.loads(r['payload'])
    if len(p.get('clubs', [])) < 3: continue          # the clue ladder needs three clubs
    P['wtb'].append(dict(id=r['id'], p=p, ok=ok(r, 'whos-that-baller')))
for r in rows('clean-sweep'):
    p = json.loads(r['payload'])
    if len(p['names']) not in (10, 15, 20): continue  # list size follows the number of players: 10, 15 or 20 names
    P['cs'].append(dict(id=r['id'], q=p['q'], note=p.get('note', ''), names=p['names'], ok=ok(r, 'clean-sweep')))
# Clean Sweep lists whose labels are counts (caps, goals) double as Ranked Highly chains
for r in rows('clean-sweep'):
    p = json.loads(r['payload']); note = p.get('note', '')
    m = re.search(r'Labels show (caps|goals)\.', note)
    labs = [x.get('l', '') for x in p['names']]
    if not m or not all(re.fullmatch(r'\d+', l) for l in labs): continue
    P['rh'].append(dict(id='cs%d' % r['id'], theme=p['q'], unit=m.group(1), note=note, chain=[[x['n'], int(x['l'])] for x in p['names']], ok=ok(r, 'clean-sweep')))
for r in rows('ranked-highly'):
    p = json.loads(r['payload'])
    P['rh'].append(dict(id=r['id'], theme=p['theme'], unit=p.get('unit', ''), chain=p['chain'], ok=ok(r, 'ranked-highly')))
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('// Generated by db/make_mp_pool.py. Multiplayer puzzle pool; server-side only, not a route.\nexport const POOL = '
                     + json.dumps(P, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('mp pool', {k: f"{sum(x['ok'] for x in v)}/{len(v)}" for k, v in P.items()})
