"""Writes functions/api/bank/_seed.js: schema + every row of tdko.db as SQL, in foreign-key order."""
import sqlite3, json, re
c=sqlite3.connect('/home/claude/db/tdko.db')
schema=open('/home/claude/db/schema.sql').read()
schema=re.sub(r'--[^\n]*','',schema)
stmts=[s.strip() for s in schema.split(';') if s.strip() and not s.strip().upper().startswith('PRAGMA')]
stmts=[re.sub(r'^CREATE TABLE ','CREATE TABLE IF NOT EXISTS ',s) for s in stmts]
stmts=[re.sub(r'^CREATE INDEX ','CREATE INDEX IF NOT EXISTS ',s) for s in stmts]
stmts=[re.sub(r'\s+',' ',s) for s in stmts]
order=['dim_game','dim_difficulty','dim_question_type','dim_nation','dim_club','dim_player','dim_competition','dim_season','dim_source','dim_date',
       'fact_question','fact_answer','fact_schedule','bridge_question_player','bridge_question_club','bridge_question_nation']
def lit(v):
    if v is None: return 'NULL'
    if isinstance(v,(int,float)): return str(v)
    return "'"+str(v).replace("'","''")+"'"
rows=[]
for t in order:
    for r in c.execute(f'SELECT * FROM {t}'):
        rows.append(f'INSERT OR IGNORE INTO {t} VALUES({",".join(lit(v) for v in r)})')
assert max(len(s) for s in rows) < 90000
js='// Generated by db/make_seed.py from the approved puzzles. Not a route (files starting with _ are ignored).\n'
js+='export const SCHEMA = '+json.dumps(stmts,ensure_ascii=False)+';\n'
js+='export const ROWS = '+json.dumps(rows,ensure_ascii=False)+';\n'
import os; os.makedirs('/home/claude/tdko-site/functions/api/bank',exist_ok=True)
open('/home/claude/tdko-site/functions/api/bank/_seed.js','w').write(js)
print(len(stmts),'schema',len(rows),'rows',len(js)//1024,'KB')

# Scheduler page data (functions/api/_schedule.js): what is set up for each game and day, and the bank's difficulty mix.
# Built from the same bank, so the Scheduler page always matches what is deployed (no reload needed).
import datetime
c.row_factory=sqlite3.Row
games=[dict(r) for r in c.execute('SELECT game_id, slug, name, per_day FROM dim_game ORDER BY menu_order')]
for g in games:
    g['days']={str(r['day_no']):[r['n'],r['draft']] for r in c.execute("""SELECT d.day_no, COUNT(*) n, SUM(q.status<>'approved') draft
        FROM fact_schedule s JOIN dim_date d USING(date_key) JOIN fact_question q USING(question_id) WHERE s.game_id=? GROUP BY d.day_no""",(g['game_id'],))}
    mix={'E':0,'M':0,'H':0,'U':0,'draft':0,'unused':0}
    for r in c.execute("""SELECT COALESCE(d.code,'U') lv, q.status, EXISTS(SELECT 1 FROM fact_schedule s WHERE s.question_id=q.question_id) used
        FROM fact_question q LEFT JOIN dim_difficulty d USING(difficulty_id) WHERE q.game_id=? AND q.status<>'retired'""",(g['game_id'],)):
        if r['status']=='approved': mix[r['lv']]+=1; mix['unused']+=0 if r['used'] else 1
        else: mix['draft']+=1
    g['mix']=mix; del g['game_id']
PAUSED={'tiki-taka-toe':'2026-12-14'}   # games taken off the menu (site-build/the-daily-kick-off.html pauseFrom)
for g in games: g['paused_from']=PAUSED.get(g['slug'])
view=dict(built=datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M'), launch='2026-11-16', last='2026-12-31', games=games)
open('/home/claude/tdko-site/functions/api/_schedule.js','w').write('// Generated by db/make_seed.py. Data for the Scheduler page; not a route.\nexport const VIEW = '+json.dumps(view,ensure_ascii=False)+';\n')
print('scheduler view written')

# Live-stat checklist (functions/api/_live.js, not a route): every flagged puzzle on the calendar from today on,
# with what to re-check and where. The daily 07:00 check reads this for tomorrow's date.
today=datetime.date.today().isoformat()
live=[]
for r in c.execute("""SELECT d.date AS date, d.day_no AS no, g.name AS game, q.ext_id, q.prompt, q.answer, q.payload, q.live_note, q.checked_on, s.title AS src, s.url
    FROM fact_schedule f JOIN fact_question q USING(question_id) JOIN dim_date d USING(date_key) JOIN dim_game g ON g.game_id=q.game_id
    LEFT JOIN dim_source s ON s.source_id=q.source_id WHERE q.live=1 AND d.date>=? ORDER BY d.day_no""",(today,)):
    r=dict(r); r['payload']=json.loads(r['payload']); live.append(r)
open('/home/claude/tdko-site/functions/api/_live.js','w').write('// Generated by db/make_seed.py. Puzzles with stats that can still change, by the day they play. Not a route.\nexport const LIVE = '+json.dumps(live,ensure_ascii=False,indent=0)+';\n')
print('live checklist', len(live))
